# %% 1. 變數與型別
# C++ :  int a = 5;  double b = 3.14;  string s = "hi";  bool f = true;
# Python:不寫型別,直接給值
a = 5
b = 3.14
s = "hi"
f = True            # ⚠ 大寫 T。False 也是大寫
nothing = None      # 相當於 C++ 的 nullptr,代表「沒有值」

# type() 問它現在是什麼型別
print(type(a), type(b), type(s), type(f), type(nothing))

# 同一個變數可以換成別的型別(C++ 不行)
a = "now I'm a string"
print(a)


# %% 2. 整數沒有上限 —— 這是跟 C++ 最大的差別之一
# C++ 的 long long 最大 9.2e18,超過就溢位變負數
# Python 的 int 是「大數」,要多大有多大
x = 2 ** 100        # ** 是次方。C++ 要用 pow(),而且是浮點數
print(x)            # 1267650600228229401496703205376,精確值
print(10 ** 30 + 1) # 不會溢位

# ⚠ 代價:慢。大數運算比 C++ 的 long long 慢很多


# %% 3. 除法 —— ★ 最容易踩的坑
# C++ :  7 / 2 == 3   (整數除整數 = 整數)
# Python: 7 / 2 == 3.5 (一律回傳浮點數!)
print(7 / 2)        # 3.5
print(7 // 2)       # 3    ← 整數除法要用 //
print(7 % 2)        # 1    取餘數,跟 C++ 一樣

# ⚠ 負數的 // 和 % 跟 C++ 不一樣!
# C++ :  -7 / 2 == -3,  -7 % 2 == -1   (往 0 截斷)
# Python: -7 // 2 == -4, -7 % 2 == 1    (往負無窮取整)
print(-7 // 2, -7 % 2)
# 好處:Python 的 % 永遠回傳非負數(除數為正時),做模運算不用再 +MOD


# %% 4. 字串
s = "Hello"
print(len(s))           # 5,相當於 s.size()
print(s[0], s[-1])      # H o   ← 負索引:-1 是最後一個,C++ 沒有
print(s.upper())        # HELLO
print(s + " World")     # 串接
print(s * 3)            # HelloHelloHello  ← 字串乘整數 = 重複

# ⚠ 字串「不能改」(immutable)
# s[0] = "J"            # 這行會報錯 TypeError
s = "J" + s[1:]         # 只能做一個新的
print(s)                # Jello


# %% 5. f-string —— 格式化輸出(最常用)
# C++ :  cout << "n = " << n << ", avg = " << fixed << setprecision(2) << avg;
# Python: 字串前面加 f,大括號裡直接放變數或運算式
n = 7
avg = 3.14159
print(f"n = {n}, avg = {avg:.2f}")      # :.2f = 小數點後 2 位
print(f"{n} squared is {n * n}")        # 大括號裡可以放運算式
print(f"[{n:5d}]")                      # 寬度 5 靠右:[    7]
print(f"[{n:<5d}]")                     # 靠左:[7    ]


# %% 6. print 的細節
print(1, 2, 3)              # 預設用空白隔開:1 2 3
print(1, 2, 3, sep=",")     # 改用逗號:1,2,3
print("no newline", end="") # 預設結尾是 \n,改掉就不換行
print(" <- same line")


# %% 7. 輸入
# C++ :  int n; cin >> n;
# Python: input() 永遠讀「一整行」,而且是字串,要自己轉型
#
#   n = int(input())                      # 一行一個整數
#   a, b = map(int, input().split())      # 一行兩個整數
#   arr = list(map(int, input().split())) # 一行一串整數
#
# 拆解最後一行:
#   input()          讀一行          "3 1 4"
#   .split()         用空白切開      ["3", "1", "4"]
#   map(int, ...)    每個轉成 int    3, 1, 4
#   list(...)        收成串列        [3, 1, 4]
#
# (這格不跑 input,因為在互動視窗會卡住等你輸入。這裡用字串模擬)
line = "3 1 4"
arr = list(map(int, line.split()))
print(arr, sum(arr))


# %% 8. 型別轉換
print(int("42") + 1)        # 字串 → 整數
print(float("3.5") * 2)     # 字串 → 浮點
print(str(42) + "!")        # 整數 → 字串
print(int(3.99))            # 3,直接截掉小數(不是四捨五入)
print(round(3.5), round(2.5))  # 4 2  ← ⚠ 銀行家捨入:.5 往偶數靠


